/**
 * 获取某地区的邮政编码提示（前 4 位，后补 "00" 为 6 位建议值）
 * @param {string} provinceName  省名
 * @param {string} cityName      市名（直辖市下得名时为区名）
 * @param {string} districtName  区县名（可为空）
 * @returns {string|null} 如 "215200" 或 null
 */
function getPostalCodeHint(provinceName, cityName, districtName) {
  // 1. 优先使用区县级别覆盖
  if (districtName && POSTAL_CODE_DISTRICT_OVERRIDE[districtName]) {
    return POSTAL_CODE_DISTRICT_OVERRIDE[districtName] + "00";
  }
  // 2. 尝试城市名（直辖市下 cityName 已是区名，直接命中）
  if (cityName && POSTAL_CODE_HINTS[cityName]) {
    return POSTAL_CODE_HINTS[cityName] + "00";
  }
  // 3. 尝试省份名（直辖市可用）
  if (provinceName && POSTAL_CODE_HINTS[provinceName]) {
    return POSTAL_CODE_HINTS[provinceName] + "00";
  }
  return null;
}

// 获取区县列表（若无数据则返回空数组）
function getDistricts(cityName) {
  return DISTRICT_MAP[cityName] || [];
}

