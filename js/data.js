// 判断是否已存在用户录入数据
function _hasRecords() {
  try { return RecordStore.count() > 0; } catch { return false; }
}

const PostmarkData = {
  /** 获取所有省份数据 */
  getAllProvinces() {
    return PROVINCE_DATA;
  },

  /** 根据 adcode 获取省份 */
  getProvince(adcode) {
    return PROVINCE_DATA.find(p => p.adcode === adcode) || null;
  },

  /** 根据名称获取省份 */
  getProvinceByName(name) {
    return PROVINCE_DATA.find(p => p.name === name) || null;
  },

  /** 获取省份的城市列表 */
  getProvinceCities(adcode) {
    const prov = this.getProvince(adcode);
    return prov ? prov.cities : [];
  },

  /** 获取省份的城市名列表 (用于表单下拉框) */
  getProvinceCityNames(provinceName) {
    // 直辖市的市级行政单位默认与省同名
    if (MUNICIPALITIES.includes(provinceName)) {
      return [provinceName];
    }
    const prov = PROVINCE_DATA.find(p => p.name === provinceName);
    return prov ? prov.cities.map(c => c.name) : [];
  },

  /** 获取区县列表 */
  getDistricts(cityName) {
    return getDistricts(cityName);
  },

  /** 获取全国汇总 */
  getNationSummary() {
    let total = 0;
    for (const p of PROVINCE_DATA) total += p.total;

    if (!_hasRecords()) {
      return { total, collected: 0, provinces: PROVINCE_DATA.length, coveredProvinces: 0, coveredCities: 0 };
    }

    const stats = RecordStore.getSummary();
    return {
      total,
      collected: stats.totalRecords,
      provinces: PROVINCE_DATA.length,
      coveredProvinces: stats.coveredProvinces,
      coveredCities: stats.coveredCities
    };
  },

  /** 获取已涉足省份数量 */
  getCoveredProvinceCount() {
    if (!_hasRecords()) return 0;
    const stats = RecordStore.getProvinceStats();
    return Object.keys(stats).length;
  },

  /** 获取用于分布图的数据（按省份） */
  getProvinceRates() {
    if (!_hasRecords()) {
      return PROVINCE_DATA.map(p => ({
        name: p.name,
        rate: 0
      }));
    }
    const provStats = RecordStore.getProvinceStats();
    return PROVINCE_DATA.map(p => {
      const collected = provStats[p.name] ? provStats[p.name].collected : 0;
      return {
        name: p.name,
        rate: p.total > 0 ? Math.round(collected / p.total * 100) : 0
      };
    });
  },

  /** 获取地图着色数据 (value = 已收集数量) */
  getMapData(level = 'province', parentAdcode = null) {
    const hasRecs = _hasRecords();
    const provStats = hasRecs ? RecordStore.getProvinceStats() : {};

    if (level === 'province') {
      return PROVINCE_DATA.map(p => {
        const collected = hasRecs
          ? (provStats[p.name] ? provStats[p.name].collected : 0)
          : 0;
        return {
          name: p.name,
          value: collected,
          collected,
          adcode: p.adcode
        };
      });
    }

    if (level === 'city' && parentAdcode) {
      const prov = this.getProvince(parentAdcode);
      if (!prov) return [];
      // 直辖市的市级地图显示区县，统计按 district 聚合
      const isMun = MUNICIPALITIES.includes(prov.name);
      const stats = hasRecs
        ? (isMun ? RecordStore.getDistrictStats(prov.name) : RecordStore.getCityStats(prov.name))
        : {};
      return prov.cities.map(c => {
        const collected = hasRecs
          ? (stats[c.name] ? stats[c.name].collected : 0)
          : 0;
        return {
          name: c.name,
          value: collected,
          collected,
          adcode: c.adcode
        };
      });
    }
    return [];
  },

  /** 按完成率排序，返回排名数据 */
  getRanking() {
    const hasRecs = _hasRecords();
    const provStats = hasRecs ? RecordStore.getProvinceStats() : {};
    return PROVINCE_DATA
      .map(p => {
        const collected = hasRecs
          ? (provStats[p.name] ? provStats[p.name].collected : 0)
          : p.collected;
        return {
          name: p.name,
          collected,
          total: p.total,
          rate: p.total > 0 ? +(collected / p.total * 100).toFixed(1) : 0,
          adcode: p.adcode
        };
      })
      .sort((a, b) => b.rate - a.rate);
  },

  /** 获取邮政编码提示 */
  getPostalCodeHint(provinceName, cityName, districtName) {
    return getPostalCodeHint(provinceName, cityName, districtName);
  }
};
